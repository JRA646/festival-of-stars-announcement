create or replace function public.get_public_festival_of_stars(p_slug text default 'festival-of-stars')
returns jsonb
language sql
security definer
set search_path=public
stable
as $$
  select jsonb_build_object(
    'event',jsonb_build_object(
      'id',e.id,'name',e.name,'description',e.description,
      'start_at',e.start_at,'end_at',e.end_at,'location',e.location
    ),
    'announcement',jsonb_build_object(
      'slug',a.slug,'published_at',a.published_at,'registration_enabled',a.registration_enabled,
      'hero_image_url',a.hero_image_url,'seo_title',a.seo_title,
      'seo_description',a.seo_description,'content',a.content
    ),
    'talents',coalesce((
      select jsonb_agg(to_jsonb(tc)-'created_at' order by tc.sort_order)
      from public.festival_talent_categories tc where tc.is_active=true
    ),'[]'::jsonb)
  )
  from public.festival_announcements a
  join public.events e on e.id=a.event_id
  where a.slug=p_slug and a.published_at is not null and a.published_at <= now() and e.is_active=true
  limit 1;
$$;

revoke all on function public.get_public_festival_of_stars(text) from public;
grant execute on function public.get_public_festival_of_stars(text) to anon,authenticated;
notify pgrst,'reload schema';
