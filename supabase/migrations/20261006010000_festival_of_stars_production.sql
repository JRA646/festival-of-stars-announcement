create table if not exists public.festival_announcements (
  event_id uuid primary key references public.events(id) on delete cascade,
  slug text not null unique,
  published_at timestamptz,
  registration_enabled boolean not null default true,
  hero_image_url text,
  seo_title text,
  seo_description text,
  content jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.festival_talent_categories (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  tagline text not null,
  description text not null,
  accent text not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.festival_registrations (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  full_name text not null,
  email text not null,
  mobile text,
  guests smallint not null default 0 check (guests between 0 and 10),
  attending_service text,
  message text,
  created_at timestamptz not null default now(),
  constraint festival_registrations_name_ck check (char_length(trim(full_name)) between 2 and 120),
  constraint festival_registrations_email_ck check (char_length(trim(email)) between 5 and 254)
);

create unique index if not exists festival_registrations_event_email_uq
  on public.festival_registrations(event_id, lower(trim(email)));

create table if not exists public.festival_talent_submissions (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  talent_category_id uuid not null references public.festival_talent_categories(id),
  full_name text not null,
  email text not null,
  mobile text,
  performance_title text not null,
  description text not null,
  sample_url text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  constraint festival_talent_name_ck check (char_length(trim(full_name)) between 2 and 120),
  constraint festival_talent_title_ck check (char_length(trim(performance_title)) between 2 and 160),
  constraint festival_talent_description_ck check (char_length(trim(description)) between 10 and 2000)
);

create table if not exists public.festival_analytics_events (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.events(id) on delete cascade,
  event_type text not null,
  path text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint festival_analytics_event_type_ck check (
    event_type in (
      'page_view','register_click','register_submit','talent_view',
      'talent_select','talent_submit','share_click','directions_click','sound_toggle'
    )
  )
);

create index if not exists festival_analytics_event_time_idx
  on public.festival_analytics_events(event_id, created_at desc);

